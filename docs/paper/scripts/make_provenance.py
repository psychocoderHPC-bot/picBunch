#!/usr/bin/env python3
"""Emit one well-formed provenance record without hand-editing JSON.

The measurement/replot worker passes the case id, the command, the produced or
consumed data files and the host metadata.  The script hashes every file it is
given, fills the case-dependent defaults (figures, axis rule, seed, host) from
``docs/paper/data/cases.json``, validates the record against
``provenance/provenance.schema.json`` and writes it to
``provenance/records/<case-id>.json`` (or ``--out``).

Example:
  python3 docs/paper/scripts/make_provenance.py \\
      --case-id hires-g10 --measurement-kind fresh-h100 \\
      --command "python3 tools/hi_compose.py ..." \\
      --data docs/paper/data/hires/hi_g10.npz \\
      --script docs/paper/scripts/render_pergamma.py \\
      --host "jureca-h100 (jrc0880)" --gpu-model "NVIDIA H100 PCIe" \\
      --cuda-version 12.4 --openpmd-version 0.16.1 --adios2-version 2.10.1 \\
      --io-backend adios2 --seed 42 --repeats 3 --statistic median \\
      --start-utc 2026-11-08T10:00:00Z --end-utc 2026-11-08T11:00:00Z \\
      --out docs/paper/provenance/records/hires-g10.json

When the executable is not on this host, give ``--binary-sha256 <hex>`` instead
of ``--binary <path>``; the record then carries the measured digest without a
local path.

For a freshly recomputed analytic/exact reference (not a GPU measurement), use
``--measurement-kind fresh-reference --reference-only``.  Record the generating
code with ``--generator name=<path-or-sha256>`` (repeatable); artifacts outside
the checkout are stored as a bare digest so the record stays valid in a fresh
clone.  A fresh-reference record needs a non-empty ``--host`` and at least one
generator digest.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER_DIR = os.path.dirname(HERE)
REPO_ROOT = os.path.dirname(os.path.dirname(PAPER_DIR))
CASES = os.path.join(PAPER_DIR, "data", "cases.json")
SCHEMA = os.path.join(PAPER_DIR, "provenance", "provenance.schema.json")

sys.path.insert(0, HERE)
import check_provenance  # noqa: E402


def _repo_path(path):
    absolute = os.path.abspath(path)
    try:
        rel = os.path.relpath(absolute, REPO_ROOT)
    except ValueError:  # different drive on Windows
        return absolute
    return absolute if rel.startswith("..") else rel


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _digest(path):
    if path is None:
        return None
    if not os.path.isfile(path):
        raise SystemExit("error: --digest path does not exist: %s" % path)
    return {"path": _repo_path(path), "sha256": _sha256(path)}


def _file_digest(path):
    if not os.path.isfile(path):
        raise SystemExit("error: data file does not exist: %s" % path)
    return {"path": _repo_path(path), "sha256": _sha256(path)}


def _load_case(case_id):
    if case_id is None:
        return {}
    with open(CASES, "r") as fh:
        registry = json.load(fh)
    try:
        return registry["cases"][case_id]
    except KeyError:
        raise SystemExit("error: case %r is not in %s" % (case_id, CASES))


def _parse_seed(text):
    if text is None or text.lower() == "none":
        return None
    parts = [p for p in text.replace(",", " ").split() if p]
    values = [int(p) for p in parts]
    return values[0] if len(values) == 1 else values


def _current_commit():
    try:
        out = subprocess.check_output(
            ["git", "-C", REPO_ROOT, "rev-parse", "HEAD"], stderr=subprocess.DEVNULL)
        return out.decode().strip()
    except (OSError, subprocess.CalledProcessError):
        return None


def build_record(a):
    case = _load_case(a.case_id)
    figures = a.figure or case.get("figures") or []
    if not figures:
        raise SystemExit("error: no figure ids given and case has none")

    data_args = a.data
    if not data_args:
        data_args = [entry["path"] for entry in case.get("source_data", [])]
    if not data_args and a.measurement_kind != "not-reproduced":
        raise SystemExit("error: provide at least one --data path")
    if not data_args:
        # A not-reproduced record documents a renderer whose campaign data is
        # still pending; it intentionally carries no data digest.
        data_args = []

    seed = case.get("seed") if a.seed is None else _parse_seed(a.seed)
    if a.seed is not None:
        seed = _parse_seed(a.seed)
    if a.seed == "none":
        seed = None

    notes = a.notes
    if notes is None:
        notes = ("Generated by make_provenance.py from case %s. "
                 "Fields the run did not record are null." % a.case_id)

    records_dir = os.path.join(PAPER_DIR, "provenance", "records")
    out = a.out or os.path.join(records_dir, "%s.json" % a.case_id)

    git_commit = a.git_commit
    if git_commit == "auto":
        git_commit = _current_commit()
    elif git_commit == "none":
        git_commit = None

    if a.binary is not None and getattr(a, "binary_sha256", None) is not None:
        raise SystemExit("error: give --binary or --binary-sha256, not both")
    def _digest_or_literal(path, literal, label):
        if path is not None and literal is not None:
            raise SystemExit("error: give --%s or --%s-sha256, not both"
                             % (label, label))
        if literal is not None:
            if re.search(r"^[0-9a-f]{64}$", literal) is None:
                raise SystemExit("error: --%s-sha256 must be 64 lowercase hex "
                                 "characters" % label)
            return {"sha256": literal}
        return _digest(path)

    config_digest = _digest_or_literal(a.config, getattr(a, "config_sha256", None),
                                       "config")
    script_digest = _digest_or_literal(a.script, getattr(a, "script_sha256", None),
                                       "script")

    binary_digest = _digest(a.binary)
    if getattr(a, "binary_sha256", None) is not None:
        if re.search(r"^[0-9a-f]{64}$", a.binary_sha256) is None:
            raise SystemExit("error: --binary-sha256 must be 64 lowercase hex "
                             "characters")
        binary_digest = {"sha256": a.binary_sha256}

    generator = {}
    for item in (a.generator or []):
        if "=" not in item:
            raise SystemExit("error: --generator expects NAME=PATH_OR_SHA256, "
                             "got %r" % item)
        name, value = item.split("=", 1)
        if re.search(r"^[A-Za-z0-9_.-]+$", name) is None:
            raise SystemExit("error: bad --generator name %r" % name)
        if re.search(r"^[0-9a-f]{64}$", value) is not None:
            generator[name] = {"sha256": value}
            continue
        if not os.path.isfile(value):
            raise SystemExit("error: --generator %s path/sha256 does not exist: "
                             "%s" % (name, value))
        digest = _sha256(value)
        rel = _repo_path(value)
        if os.path.isabs(rel):
            # Keep the record valid in a fresh clone: a bare digest, no path.
            generator[name] = {"sha256": digest}
        else:
            generator[name] = {"path": rel, "sha256": digest}

    record = {
        "case_id": a.case_id,
        "figure_ids": figures,
        "measurement_kind": a.measurement_kind,
        "command": a.command,
        "config_sha256": config_digest,
        "binary_sha256": binary_digest,
        "data_sha256": [_file_digest(p) for p in data_args],
        "script_sha256": script_digest,
        "host": a.host if a.host is not None else case.get("host"),
        "gpu_model": a.gpu_model,
        "cuda_version": a.cuda_version,
        "openpmd_version": a.openpmd_version,
        "adios2_version": a.adios2_version,
        "io_backend": a.io_backend,
        "seed": seed,
        "start_utc": a.start_utc,
        "end_utc": a.end_utc,
        "git_commit": git_commit,
        "axis_rule": a.axis_rule if a.axis_rule is not None else case.get("propagation_axis"),
        "repeats": a.repeats,
        "statistic": a.statistic,
        "notes": notes,
    }
    if a.reference_only:
        record["reference_only"] = True
    if generator:
        record["generator"] = generator
    return record, out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--case-id", required=True)
    ap.add_argument("--measurement-kind", default="fresh-h100",
                    choices=["fresh-h100", "fresh-reference",
                             "legacy-reduced", "not-reproduced"])
    ap.add_argument("--reference-only", action="store_true",
                    help="the figure plots a freshly recomputed reference, not "
                         "a measured PIC field (required for fresh-reference)")
    ap.add_argument("--generator", action="append", default=None,
                    metavar="NAME=PATH_OR_SHA256",
                    help="digest of a code/input that generated a fresh "
                         "reference (repeatable)")
    ap.add_argument("--command", default=None)
    ap.add_argument("--figure", action="append", default=None,
                    help="figure id (repeatable; default: the case's figures)")
    ap.add_argument("--data", action="append", default=None,
                    help="data file whose sha256 is recorded (repeatable)")
    ap.add_argument("--config", default=None, help="config file to hash")
    ap.add_argument("--binary", default=None, help="binary/executable to hash")
    ap.add_argument("--binary-sha256", default=None,
                    help="literal sha256 of the binary when it is not available "
                         "locally (the path is then omitted)")
    ap.add_argument("--script", default=None, help="measurement/replot script to hash")
    ap.add_argument("--config-sha256", default=None,
                    help="literal sha256 of the measurement config when only the "
                         "digest is available")
    ap.add_argument("--script-sha256", default=None,
                    help="literal sha256 of the measurement script when only the "
                         "digest is available")
    ap.add_argument("--host", default=None)
    ap.add_argument("--gpu-model", default=None)
    ap.add_argument("--cuda-version", default=None)
    ap.add_argument("--openpmd-version", default=None)
    ap.add_argument("--adios2-version", default=None)
    ap.add_argument("--io-backend", default=None)
    ap.add_argument("--seed", default=None, help="integer, comma-separated list, or 'none'")
    ap.add_argument("--start-utc", default=None)
    ap.add_argument("--end-utc", default=None)
    ap.add_argument("--git-commit", default="auto",
                    help="7-40 hex chars, 'auto' for HEAD, or 'none'")
    ap.add_argument("--axis-rule", default=None)
    ap.add_argument("--repeats", type=int, default=None)
    ap.add_argument("--statistic", default=None)
    ap.add_argument("--notes", default=None)
    ap.add_argument("--out", default=None,
                    help="record path (default: provenance/records/<case-id>.json)")
    ap.add_argument("--stdout", action="store_true",
                    help="print the record instead of writing a file")
    a = ap.parse_args(argv)

    record, out = build_record(a)

    with open(SCHEMA, "r") as fh:
        schema = json.load(fh)
    errors = check_provenance.validate(record, schema, schema)
    if errors:
        for err in errors:
            print("error: " + err, file=sys.stderr)
        return 1

    text = json.dumps(record, indent=2, sort_keys=True) + "\n"
    if a.stdout:
        sys.stdout.write(text)
    else:
        os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
        with open(out, "w") as fh:
            fh.write(text)
        print(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
