# Reproduce the velocity-binning calibration record from the committed
# accuracy points. The script does not re-run the campaign: it reads
# docs/measurements/velocity_bin_calibration.csv and reports what the archived
# rows support. If the optional model_sum column is present it also reports the
# per-row effective constant C = measured_worst_rel_error / model_sum.
#
# Usage:
#   tools/velocity-bins/calibrate_velocity_bins.py            # print the record
#   tools/velocity-bins/calibrate_velocity_bins.py --write    # refresh the .txt
#   tools/velocity-bins/calibrate_velocity_bins.py --csv FILE

from __future__ import annotations

import argparse
import csv
import pathlib
import sys

SHIPPED_C = 1.0
TARGET = 1.0e-3


def parse_args() -> argparse.Namespace:
    repo = pathlib.Path(__file__).resolve().parents[2]
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--csv",
        type=pathlib.Path,
        default=repo / "docs/measurements/velocity_bin_calibration.csv",
    )
    p.add_argument(
        "--write",
        action="store_true",
        help="write docs/measurements/velocity_bin_calibration_fit.txt",
    )
    return p.parse_args()


def read_rows(path: pathlib.Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    header: list[str] | None = None
    with path.open(newline="") as f:
        body = (line for line in f if not line.lstrip().startswith("#"))
        for rec in csv.DictReader(body):
            if header is None:
                header = list(rec)
            if not rec.get("case"):
                continue
            rows.append({k: (v or "").strip() for k, v in rec.items()})
    if header is None:
        raise SystemExit(f"{path}: no CSV header found")
    return rows


def render(rows: list[dict[str, str]], csv_path: pathlib.Path) -> str:
    repo = pathlib.Path(__file__).resolve().parents[2]
    try:
        source = csv_path.resolve().relative_to(repo).as_posix()
    except ValueError:
        source = csv_path.as_posix()
    lines = [
        "# MV1 velocity-binning calibration record",
        f"# source: {source}",
        "# generated by tools/velocity-bins/calibrate_velocity_bins.py",
        "",
        "model: modelError = C * sum_b (|q_b|/Q) * (gamma_b*Delta_theta_b"
        " + Delta_gamma_b/gamma_b + delta_gamma_b)",
        f"shipped constant kDefaultVelocityModelConstant = {SHIPPED_C:g}",
    ]
    for key in ("host", "campaign_commit", "campaign", "date"):
        values = sorted({r.get(key, "") for r in rows if r.get(key)})
        if values:
            lines.append(f"{key}: {', '.join(values)}")
    lines += [
        "",
        "## Archived accuracy points",
        "",
        "| case | boxes | measured worst rel error | target |",
        "| --- | ---: | ---: | ---: |",
    ]
    cases: dict[str, list[dict[str, str]]] = {}
    for row in rows:
        case = row["case"]
        cases.setdefault(case, []).append(row)
        lines.append(
            f"| {case} | {row['box_count']} | {row['measured_worst_rel_error']} "
            f"| {TARGET:g} |"
        )

    lines += ["", "## Reproduction verdict", ""]
    for case, group in cases.items():
        met = [
            r
            for r in group
            if float(r["measured_worst_rel_error"]) <= TARGET
        ]
        if met:
            first = min(met, key=lambda r: int(r["box_count"]))
            lines.append(
                f"- {case}: archived points reach {TARGET:g} at "
                f"{first['box_count']} boxes "
                f"({first['measured_worst_rel_error']})."
            )
        else:
            lines.append(
                f"- {case}: no archived point reaches {TARGET:g}; the "
                "largest archived count is still above target."
            )

    models = [
        r
        for r in rows
        if r.get("model_sum")
        and float(r["model_sum"]) != 0.0
    ]
    lines += ["", "## Fit", ""]
    if models:
        consts = [
            float(r["measured_worst_rel_error"]) / float(r["model_sum"])
            for r in models
        ]
        lines.append(
            "model_sum is present; per-row C = measured/model_sum ranges "
            f"{min(consts):.6g} .. {max(consts):.6g}, mean "
            f"{sum(consts) / len(consts):.6g}."
        )
    else:
        lines += [
            "No model_sum column is archived. The original 1/2/4/8-box rows, "
            "the per-box model sums and the --fit output from "
            "pr24-20261102 were not committed.",
            f"C = {SHIPPED_C:g} is an assumption, not a reproduced fit. It is "
            "conservative only where the measured error is at or below the "
            "requested target; the 5 degree angular-spread case above is a "
            "documented unsupported regime.",
            "",
            "To refit, rerun the campaign with picBunchVelocityBinsMeasure and "
            "compare_velocity_bins.py --fit, then add the model_sum values to "
            "the CSV and run this script again.",
        ]
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    rows = read_rows(args.csv)
    report = render(rows, args.csv)
    if args.write:
        out = args.csv.parent / "velocity_bin_calibration_fit.txt"
        out.write_text(report)
        print(out)
    else:
        sys.stdout.write(report)


if __name__ == "__main__":
    main()
