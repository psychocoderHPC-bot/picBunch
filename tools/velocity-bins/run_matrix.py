def canonical_cases(names: Sequence[str]) -> List[str]:
    present = set(names)
    known = [name for name in CASE_ORDER if name in present]
    extra = sorted(present - set(known))
    return known + extra


def discover_cases(cases_dir: Path) -> List[str]:
    meta = sorted(cases_dir.glob("*.meta.json"))
    if meta:
        suffix = ".meta.json"
        names = [p.name[: -len(suffix)] for p in meta]
    else:
        names = sorted(p.stem for p in cases_dir.glob("*.bunch"))
    if not names:
        raise MatrixError(
            f"no cases found in {cases_dir}: expected <case>.meta.json or <case>.bunch"
        )
    return canonical_cases(names)


def bunch_file(cases_dir: Path, case: str, require: bool) -> Path:
    path = cases_dir / f"{case}.bunch"
    if path.exists():
        return path
    meta = cases_dir / f"{case}.meta.json"
    if meta.exists():
        try:
            payload = json.loads(meta.read_text())
        except (OSError, ValueError):
            payload = {}
        for key in ("bunch", "bunch_file", "file", "path"):
            value = payload.get(key)
            if isinstance(value, str):
                candidate = Path(value)
                if not candidate.is_absolute():
                    candidate = cases_dir / candidate
                if candidate.exists():
                    return candidate
    if require:
        raise MatrixError(f"missing bunch file for case {case!r} under {cases_dir}")
    return path  # dry-run: name is enough


def build_plan(
    cases: Sequence[str], rules: Sequence[str], bins: Sequence[int], lanes: int
) -> List[Run]:
    n_matrix = len(cases) * len(rules) * len(bins)
    runs: List[Run] = []
    for case_index, case in enumerate(cases):
        for rule_index, rule in enumerate(rules):
            for bin_index, k in enumerate(bins):
                index = case_index * len(rules) * len(bins) + rule_index * len(bins) + bin_index
                runs.append(
                    Run(
                        index=index,
                        lane=index % lanes,
                        case=case,
                        rule=rule,
                        kind="matrix",
                        requested_bins=int(k),
                        run_id=f"{case}_{rule}_K{k}",
                    )
                )
        # Automatic-count runs are appended after the 54 matrix runs, so the
        # six of them still distribute evenly over the lanes.
        index = n_matrix + case_index
        runs.append(
            Run(
                index=index,
                lane=index % lanes,
                case=case,
                rule=AUTO_RULE,
                kind="auto_count",
                requested_bins=None,
                run_id=f"{case}_auto_Kauto",
            )
        )
    runs.sort(key=lambda run: run.index)
    return runs


def lane_counts(runs: Sequence[Run], lanes: int) -> List[int]:
    counts = [0] * lanes
    for run in runs:
        counts[run.lane] += 1
    return counts


