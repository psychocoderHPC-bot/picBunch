class MatrixError(RuntimeError):
    """A run, a manifest, or the output tree is not usable."""


@dataclasses.dataclass(frozen=True)
class Run:
    index: int
    lane: int
    case: str
    rule: str
    kind: str  # "matrix" or "auto_count"
    requested_bins: Optional[int]
    run_id: str

    @property
    def output_name(self) -> str:
        return f"{self.run_id}.json"

    @property
    def auto_count(self) -> bool:
        return self.kind == "auto_count"


