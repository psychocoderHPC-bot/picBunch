def _parse_triple(text: str, label: str) -> tuple:
    try:
        values = tuple(float(v) for v in text.split(","))
    except ValueError:
        raise MatrixError(f"{label} expects three comma-separated numbers, got {text!r}")
    if len(values) != 3 or any(not math.isfinite(v) for v in values):
        raise MatrixError(f"{label} expects three finite values, got {text!r}")
    return values


def _parse_grid(text: str) -> tuple:
    values = _parse_triple(text, "--grid")
    if any(v != int(v) or v < 1 for v in values):
        raise MatrixError(f"--grid expects three positive integers, got {text!r}")
    return tuple(int(v) for v in values)


def resolve_geometry(args: argparse.Namespace) -> dict:
    """Named baseline plus explicit overrides; centre defaults to domain centre."""
    base = GEOMETRIES[args.geometry]
    cell = _parse_triple(args.cell, "--cell") if args.cell else tuple(base["cell"])
    grid = _parse_grid(args.grid) if args.grid else tuple(base["grid"])
    origin = _parse_triple(args.origin, "--origin") if args.origin else tuple(base["origin"])
    center = (
        _parse_triple(args.center, "--center")
        if args.center
        else tuple(origin[a] + 0.5 * grid[a] * cell[a] for a in range(3))
    )
    for axis, name in enumerate(("x", "y", "z")):
        if cell[axis] <= 0.0:
            raise MatrixError(f"cell[{name}] must be > 0")
        margin = TSC_SUPPORT_CELLS * cell[axis]
        lo = center[axis] - R_BUNCH_M - margin
        hi = center[axis] + R_BUNCH_M + margin
        dlo = origin[axis]
        dhi = origin[axis] + grid[axis] * cell[axis]
        if lo < dlo - 1e-12 or hi > dhi + 1e-12:
            raise MatrixError(
                f"geometry {name}: cube + TSC support [{lo:.6e}, {hi:.6e}] m "
                f"does not fit in the domain [{dlo:.6e}, {dhi:.6e}] m"
            )
    return {
        "name": args.geometry,
        "cell": cell,
        "grid": grid,
        "origin": origin,
        "center": center,
    }


def cpu_workers(requested: int, jobs: int) -> int:
    if requested > 0:
        return requested
    total = os.cpu_count() or 1
    return max(1, min(8, total // max(1, jobs)))


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    out_dir: Path = args.out
    cases_dir: Path = args.cases_dir
    geometry = args.geometry

    if args.generate:
        gen_argv = generator_argv(args.python, args.gen_script, cases_dir, geometry)
        if args.dry_run:
            print(f"GENERATE: {shlex.join(gen_argv)}")
        else:
            try:
                if not args.gen_script.is_file():
                    raise MatrixError(f"generator not found: {args.gen_script}")
                run_process(gen_argv, out_dir / ".work" / "generate.log",
                            args.timeout if args.timeout > 0 else None, "generate")
            except MatrixError as exc:
                print(f"run_matrix: {exc}", file=sys.stderr)
                return 1

    try:
        try:
            cases = discover_cases(cases_dir)
        except MatrixError:
            # A dry run that plans the generator has no case files yet; the
            # generator's canonical six cases are the plan.
            if not (args.dry_run and args.generate):
                raise
            cases = list(CASE_ORDER)
        runs = build_plan(cases, args.rules, args.bins, args.lanes)
        n_matrix = len(cases) * len(args.rules) * len(args.bins)
        n_auto = len(cases)
        counts = lane_counts(runs, args.lanes)
        compare_workers = cpu_workers(args.compare_workers, args.jobs)
    except MatrixError as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1

    if args.dry_run:
        print(f"CASES {len(cases)}: {' '.join(cases)}")
        print(
            "GEOMETRY name={} cell={} grid={} origin={} center={}".format(
                geometry["name"],
                format_triple(geometry["cell"]),
                format_triple(geometry["grid"]),
                format_triple(geometry["origin"]),
                format_triple(geometry["center"]),
            )
        )
        print(f"PROFILE {args.profile}")
        print(
            f"MATRIX {n_matrix} explicit + {n_auto} auto = {n_matrix + n_auto} runs; "
            f"lanes={args.lanes} per_lane={counts}"
        )
        for run in runs:
            bunch = bunch_file(cases_dir, run.case, require=False)
            prefix = out_dir / ".work" / run.run_id / run.run_id
            m_argv = measurement_argv(args.binary, bunch, run, prefix, geometry)
            c_argv = compare_argv(
                args.python, args.compare, prefix, run.requested_bins,
                compare_workers, reference_cache_dir(out_dir)
            )
            print(
                f"RUN {run.index:02d} lane={run.lane} id={run.run_id} "
                f"kind={run.kind} K={run.requested_bins if run.requested_bins else 'auto'}"
            )
            print(f"  measure: {shlex.join(m_argv)}")
            print(f"  compare: {shlex.join(c_argv)}")
        for lane in range(args.lanes):
            members = [run.run_id for run in runs if run.lane == lane]
            print(f"LANE {lane} ({len(members)}): {' '.join(members)}")
        print(
            "PLAN_SUMMARY "
            + json.dumps(
                {
                    "cases": len(cases),
                    "matrix": n_matrix,
                    "auto_count": n_auto,
                    "total": n_matrix + n_auto,
                    "lanes": args.lanes,
                    "per_lane": counts,
                    "geometry": geometry,
                    "profile": args.profile,
                    "auto_count_bins_arg": AUTO_COUNT_BINS_ARG,
                    "deterministic_deposit": True,
                    "reference_nodes": "mask",
                    "reference_cache": str(reference_cache_dir(out_dir)),
                },
                sort_keys=True,
            )
        )
        return 0

    try:
        if not Path(args.binary).is_file():
            raise MatrixError(f"--binary is not a file: {args.binary}")
        if not os.access(args.binary, os.X_OK):
            raise MatrixError(f"--binary is not executable: {args.binary}")
        if not args.compare.is_file():
            raise MatrixError(f"comparison script not found: {args.compare}")
        for case in cases:
            bunch_file(cases_dir, case, require=True)
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / ".work").mkdir(parents=True, exist_ok=True)
    except (MatrixError, OSError) as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1

    selected = [run for run in runs if run.lane == args.lane]
    print(
        f"PLAN {n_matrix} explicit + {n_auto} auto = {n_matrix + n_auto} runs; "
        f"this lane {args.lane}/{args.lanes} runs {len(selected)}",
        flush=True,
    )
    for lane in range(args.lanes):
        members = [run.run_id for run in runs if run.lane == lane]
        print(f"LANE {lane} ({len(members)}): {' '.join(members)}", flush=True)

    print_lock = threading.Lock()
    rows_by_index: Dict[int, dict] = {}
    timeout = args.timeout if args.timeout > 0 else None

    def work(run: Run) -> dict:
        return execute_run(
            run,
            binary=args.binary,
            cases_dir=cases_dir,
            out_dir=out_dir,
            python=args.python,
            compare=args.compare,
            geometry=geometry,
            profile=args.profile,
            compare_workers=compare_workers,
            timeout=timeout,
            resume=args.resume,
            print_lock=print_lock,
        )

    try:
        if args.jobs == 1:
            for run in selected:
                rows_by_index[run.index] = work(run)
        else:
            with cf.ThreadPoolExecutor(max_workers=args.jobs) as pool:
                futures = {pool.submit(work, run): run for run in selected}
                for future in cf.as_completed(futures):
                    run = futures[future]
                    rows_by_index[run.index] = future.result()
    except MatrixError as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:  # noqa: BLE001 - report worker failures clearly
        print(f"run_matrix: unexpected failure: {exc}", file=sys.stderr)
        return 1

    lane_rows = [rows_by_index[run.index] for run in selected]
    lane_rows.sort(key=lambda row: row["index"])
    atomic_write_json(
        out_dir / f"manifest.lane{args.lane}of{args.lanes}.json",
        {
            "schema": SCHEMA,
            "lane": args.lane,
            "lanes": args.lanes,
            "geometry": dict(geometry),
            "profile": args.profile,
            "runs": lane_rows,
        },
    )

    try:
        all_rows = merge_lane_manifests(out_dir, args.lanes)
        payload = assemble_manifest(
            lane_rows,
            all_rows,
            lane=args.lane,
            lanes=args.lanes,
            out_dir=out_dir,
            expected_matrix=n_matrix,
            expected_auto=n_auto,
            binary=args.binary,
            cases_dir=cases_dir,
            bins=args.bins,
            rules=args.rules,
            geometry=geometry,
            geometry_name=geometry["name"],
            profile=args.profile,
        )
    except MatrixError as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1

    atomic_write_json(out_dir / "manifest.json", payload)
    missing = payload["missing_metrics"]
    print(
        "MISSING_METRICS " + json.dumps(missing, sort_keys=True),
        flush=True,
    )
    if payload["complete"]:
        print(
            f"MANIFEST complete rows={payload['counts']['rows']} "
            f"explicit={payload['counts']['explicit']} auto={payload['counts']['auto']}",
            flush=True,
        )
    else:
        pending = [i for i in range(args.lanes)
                   if not (out_dir / f"manifest.lane{i}of{args.lanes}.json").exists()]
        print(
            f"MANIFEST partial lane={args.lane}/{args.lanes} "
            f"rows={payload['counts']['rows']} pending_lanes={pending}",
            flush=True,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
