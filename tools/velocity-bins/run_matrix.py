"""Run the nextTests.md section 4 velocity-binning matrix.

For each synthetic bunch generated by ``gen_synthetic_bunches.py`` this driver
runs the measurement binary for the three edge rules (``uniform``,
``adaptive``, ``auto``) at ``K in {2, 4, 8}`` and once with the automatic bin
count.  That is 54 + 6 = 60 runs for the six spec bunches.

Each run is a single measurement invocation followed by
``compare_velocity_bins.py`` (the spec's TSC-convolved continuum reference).
The binary's ``PREFIX_compare.json`` is copied unchanged to
``<case>_<rule>_K<K>.json`` or ``<case>_auto_Kauto.json``; this driver never
re-implements the reference.

The measured outputs do not contain every metric named in nextTests.md
section 6.  Missing metrics are never invented: each manifest row carries a
``missing_metrics`` list and the driver prints a machine-readable summary.
See ``MISSING_METRIC_NOTES`` for the exact gaps.

Usage:
  run_matrix.py --binary PATH --cases-dir DIR --out DIR [--lane I --lanes N]
                [--bins 2 4 8] [--rules uniform adaptive auto] [--jobs 1]
                [--dry-run] [--resume] [--timeout SEC]
"""

from __future__ import annotations

import argparse
import concurrent.futures as cf
import dataclasses
import glob
import hashlib
import json
import os
import shlex
import shutil
import subprocess
import sys
import threading
import time
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

SCHEMA = "picbunch.velocity-matrix/v1"
CASE_ORDER = ("uniform", "two_cluster", "core_halo", "exp_tail", "skewed", "single_velocity")
DEFAULT_BINS = (2, 4, 8)
DEFAULT_RULES = ("uniform", "adaptive", "auto")
AUTO_RULE = "auto"

MISSING_METRIC_NOTES = {
    "far_field_rel": (
        "compare_velocity_bins.py has no 2R-offset far-field shell: error_stats() "
        "is evaluated only on nodes within 16 cells of a particle (distance bands), "
        "and outside_window_roundoff is max|mesh|, not a reference error."
    ),
    "p99_rel": (
        "compare_velocity_bins.py stores only the per-component maximum relative "
        "error (runs[B].mesh_vs_T.rel); no 99th percentile is emitted."
    ),
    "rms_rel": (
        "compare_velocity_bins.py stores only the per-component maximum relative "
        "error (runs[B].mesh_vs_T.rel); no RMS is emitted."
    ),
    "startup_us": (
        "the measurement meta file has no bin_derive_ms line (older binary); this "
        "is the edge-selection/derivation cost."
    ),
    "nonempty_bins": (
        "the measurement meta file has no box_of/bins_used lines, so the number "
        "of occupied boxes cannot be recovered."
    ),
    "proxy_error": "the comparison JSON has no model_error entry for this run.",
    "chosen_bins": "neither the report nor the meta file exposes bins_used.",
    "wall_time_s": "a resumed run has no recoverable wall time.",
    "in_bunch_rel": "the per-run comparison JSON has no mesh_vs_T.rel vector.",
    "in_bunch_max": "the per-run comparison JSON has no mesh_vs_T.worst_rel.",
}


class MatrixError(RuntimeError):
    """A run, a manifest, or the output tree is not usable."""


@dataclasses.dataclass(frozen=True)
class Run:
    index: int
    lane: int
    case: str
    rule: str
    kind: str  # "matrix" or "auto_count"
    requested_bins: Optional[int]
    run_id: str

    @property
    def output_name(self) -> str:
        return f"{self.run_id}.json"

    @property
    def auto_count(self) -> bool:
        return self.kind == "auto_count"


# ---------------------------------------------------------------------------
# planning


def canonical_cases(names: Sequence[str]) -> List[str]:
    present = set(names)
    known = [name for name in CASE_ORDER if name in present]
    extra = sorted(present - set(known))
    return known + extra


def discover_cases(cases_dir: Path) -> List[str]:
    meta = sorted(cases_dir.glob("*.meta.json"))
    if meta:
        suffix = ".meta.json"
        names = [p.name[: -len(suffix)] for p in meta]
    else:
        names = sorted(p.stem for p in cases_dir.glob("*.bunch"))
    if not names:
        raise MatrixError(
            f"no cases found in {cases_dir}: expected <case>.meta.json or <case>.bunch"
        )
    return canonical_cases(names)


def bunch_file(cases_dir: Path, case: str, require: bool) -> Path:
    path = cases_dir / f"{case}.bunch"
    if path.exists():
        return path
    meta = cases_dir / f"{case}.meta.json"
    if meta.exists():
        try:
            payload = json.loads(meta.read_text())
        except (OSError, ValueError):
            payload = {}
        for key in ("bunch", "bunch_file", "file", "path"):
            value = payload.get(key)
            if isinstance(value, str):
                candidate = Path(value)
                if not candidate.is_absolute():
                    candidate = cases_dir / candidate
                if candidate.exists():
                    return candidate
    if require:
        raise MatrixError(f"missing bunch file for case {case!r} under {cases_dir}")
    return path  # dry-run: name is enough


def build_plan(
    cases: Sequence[str], rules: Sequence[str], bins: Sequence[int], lanes: int
) -> List[Run]:
    n_matrix = len(cases) * len(rules) * len(bins)
    runs: List[Run] = []
    for case_index, case in enumerate(cases):
        for rule_index, rule in enumerate(rules):
            for bin_index, k in enumerate(bins):
                index = case_index * len(rules) * len(bins) + rule_index * len(bins) + bin_index
                runs.append(
                    Run(
                        index=index,
                        lane=index % lanes,
                        case=case,
                        rule=rule,
                        kind="matrix",
                        requested_bins=int(k),
                        run_id=f"{case}_{rule}_K{k}",
                    )
                )
        # Automatic-count runs are appended after the 54 matrix runs, so the
        # six of them still distribute evenly over the lanes.
        index = n_matrix + case_index
        runs.append(
            Run(
                index=index,
                lane=index % lanes,
                case=case,
                rule=AUTO_RULE,
                kind="auto_count",
                requested_bins=None,
                run_id=f"{case}_auto_Kauto",
            )
        )
    runs.sort(key=lambda run: run.index)
    return runs


def lane_counts(runs: Sequence[Run], lanes: int) -> List[int]:
    counts = [0] * lanes
    for run in runs:
        counts[run.lane] += 1
    return counts


# ---------------------------------------------------------------------------
# command lines and manifest helpers


def measurement_argv(
    binary: str,
    bunch: Path,
    run: Run,
    prefix: Path,
    auto_count_arg: str,
    auto_count_edges: str = AUTO_RULE,
) -> List[str]:
    argv = [
        binary,
        "--bunch",
        str(bunch),
    ]
    if run.auto_count:
        argv += ["--bins", auto_count_arg, "--velocity-bin-edges", auto_count_edges]
    else:
        argv += ["--bins", str(run.requested_bins), "--velocity-bin-edges", run.rule]
    argv += ["--output", str(prefix)]
    return argv


def compare_argv(
    python: str,
    compare: Path,
    prefix: Path,
    bins: Optional[int],
    workers: int,
) -> List[str]:
    chosen = "<chosen_bins>" if bins is None else str(bins)
    return [python, str(compare), str(prefix), "--bins", chosen, "--workers", str(workers)]


def parse_meta(path: Path) -> Dict[str, List[str]]:
    meta: Dict[str, List[str]] = {}
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        for line in handle:
            fields = line.split()
            if fields:
                meta[fields[0]] = fields[1:]
    return meta


def meta_scalar(meta: Dict[str, List[str]], key: str) -> Optional[str]:
    values = meta.get(key)
    return values[0] if values else None


def discover_run_meta(prefix: Path) -> Path:
    matches = sorted(glob.glob(str(prefix) + "_meta_B*.txt"))
    if not matches:
        raise MatrixError(f"measurement produced no meta file: {prefix}_meta_B*.txt")
    if len(matches) > 1:
        raise MatrixError(
            "measurement produced several meta files for one invocation "
            f"({', '.join(os.path.basename(m) for m in matches)}); the stale work "
            "directory must be cleaned or --resume used"
        )
    return Path(matches[0])


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def atomic_write_json(path: Path, payload: object) -> None:
    tmp = path.with_name(path.name + ".tmp")
    with tmp.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=1, sort_keys=True)
        handle.write("\n")
    os.replace(tmp, path)


def valid_run_output(path: Path) -> Optional[dict]:
    """Parse an output JSON; return None when it is not a usable compare file."""
    if not path.exists():
        return None
    if path.stat().st_size == 0:
        raise MatrixError(f"output {path} is zero bytes")
    try:
        payload = json.loads(path.read_text())
    except (OSError, ValueError) as exc:
        raise MatrixError(f"output {path} is not valid JSON: {exc}") from exc
    runs = payload.get("runs")
    if not isinstance(runs, dict) or not runs:
        raise MatrixError(f"output {path} has no non-empty 'runs' object")
    return payload


def compare_bins_key(payload: dict) -> int:
    keys = list(payload.get("runs", {}).keys())
    if len(keys) != 1:
        raise MatrixError(
            "expected exactly one bin count in the comparison JSON, found "
            f"{keys!r}"
        )
    try:
        return int(keys[0])
    except ValueError as exc:
        raise MatrixError(f"comparison JSON run key is not an integer: {keys[0]!r}") from exc


def missing_for_run(
    startup_us: Optional[float],
    nonempty_bins: Optional[int],
    compare_run: dict,
) -> Tuple[List[str], List[str]]:
    """Return (missing keys, notes) for one run."""
    present = {
        "startup_us": startup_us is not None,
        "nonempty_bins": nonempty_bins is not None,
        "proxy_error": isinstance(compare_run.get("model_error"), (int, float)),
        "far_field_rel": False,
        "p99_rel": False,
        "rms_rel": False,
    }
    stats = compare_run.get("mesh_vs_T")
    if isinstance(stats, dict):
        present["in_bunch_rel"] = bool(stats.get("rel"))
        present["far_field_rel"] = any(
            isinstance(compare_run.get(key), dict)
            and bool(compare_run[key].get("rel"))
            for key in ("far_field_rel", "far_field", "far_field_shell")
        ) or any(
            isinstance(stats.get(key), (list, tuple)) and len(stats.get(key, [])) == 6
            for key in ("far_field_rel", "far_field", "far_field_shell")
        )
        present["p99_rel"] = any(
            key in stats for key in ("p99_rel", "rel_p99", "p99")
        ) or any(key in compare_run for key in ("p99_rel", "rel_p99", "p99"))
        present["rms_rel"] = any(
            key in stats for key in ("rms_rel", "rel_rms", "rms")
        ) or any(key in compare_run for key in ("rms_rel", "rel_rms", "rms"))
    else:
        present["in_bunch_rel"] = False
    missing = [key for key, ok in present.items() if not ok]
    notes = [MISSING_METRIC_NOTES[k] for k in missing if k in MISSING_METRIC_NOTES]
    return missing, notes


def manifest_row(
    run: Run,
    output: Path,
    out_dir: Path,
    chosen_bins: Optional[int],
    startup_us: Optional[float],
    nonempty_bins: Optional[int],
    proxy_error: Optional[float],
    wall_time_s: Optional[float],
    measure_wall_s: Optional[float],
    compare_wall_s: Optional[float],
    compare_payload: dict,
    missing: Sequence[str],
    notes: Sequence[str],
) -> dict:
    try:
        rel_output = os.path.relpath(output, out_dir)
    except ValueError:
        rel_output = str(output)
    return {
        "id": run.run_id,
        "index": run.index,
        "lane": run.lane,
        "case": run.case,
        "rule": run.rule,
        "kind": run.kind,
        "auto_count": run.auto_count,
        "requested_bins": run.requested_bins,
        "chosen_bins": chosen_bins,
        "output": rel_output,
        "sha256": sha256_file(output),
        "wall_time_s": wall_time_s,
        "measure_wall_s": measure_wall_s,
        "compare_wall_s": compare_wall_s,
        "startup_us": startup_us,
        "nonempty_bins": nonempty_bins,
        "proxy_error": proxy_error,
        "compare_bins_key": str(chosen_bins) if chosen_bins is not None else None,
        "missing_metrics": list(missing),
        "missing_metric_notes": list(notes),
        "status": "ok",
    }


