def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    here = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", required=True, help="measurement binary (measure_velocity_bins)")
    parser.add_argument("--cases-dir", required=True, type=Path,
                        help="directory with <case>.bunch and <case>.meta.json")
    parser.add_argument("--out", required=True, type=Path, help="output directory")
    parser.add_argument("--lane", type=int, default=0, help="this lane index (default 0)")
    parser.add_argument("--lanes", type=int, default=1, help="number of lanes (default 1)")
    parser.add_argument("--bins", nargs="+", type=int, default=list(DEFAULT_BINS))
    parser.add_argument("--rules", nargs="+", default=list(DEFAULT_RULES),
                        choices=list(DEFAULT_RULES))
    parser.add_argument("--jobs", type=int, default=1, help="concurrent runs in this lane")
    parser.add_argument("--dry-run", action="store_true",
                        help="print the complete run plan and exit")
    parser.add_argument("--resume", action="store_true",
                        help="keep valid existing outputs; fail on unusable ones")
    parser.add_argument("--timeout", type=float, default=0.0,
                        help="per-subprocess timeout in seconds (0 = none)")
    parser.add_argument("--compare", type=Path,
                        default=here / "compare_velocity_bins.py",
                        help="path to compare_velocity_bins.py")
    parser.add_argument("--python", default=sys.executable,
                        help="Python interpreter used for compare_velocity_bins.py")
    parser.add_argument("--compare-workers", type=int, default=0,
                        help="workers for compare_velocity_bins.py (0 = cpu/jobs)")
    parser.add_argument("--auto-count-arg", default="auto",
                        help="value passed to --bins for the automatic count "
                             "(default 'auto'; pass '0' if the binary maps 0 to auto)")
    parser.add_argument("--auto-count-edges", default=AUTO_RULE,
                        help="edge rule passed for automatic-count runs (default auto)")
    args = parser.parse_args(argv)

    if args.lanes < 1:
        parser.error("--lanes must be >= 1")
    if not (0 <= args.lane < args.lanes):
        parser.error("--lane must satisfy 0 <= lane < lanes")
    if args.jobs < 1:
        parser.error("--jobs must be >= 1")
    if args.timeout < 0:
        parser.error("--timeout must be >= 0")
    if not args.bins or any(k < 1 for k in args.bins):
        parser.error("--bins values must be >= 1")
    if len(set(args.bins)) != len(args.bins):
        parser.error("--bins values must be unique")
    args.auto_count_arg = str(args.auto_count_arg)
    return args


def cpu_workers(requested: int, jobs: int) -> int:
    if requested > 0:
        return requested
    total = os.cpu_count() or 1
    return max(1, min(8, total // max(1, jobs)))


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parse_args(argv)
    out_dir: Path = args.out
    cases_dir: Path = args.cases_dir

    try:
        cases = discover_cases(cases_dir)
        runs = build_plan(cases, args.rules, args.bins, args.lanes)
        n_matrix = len(cases) * len(args.rules) * len(args.bins)
        n_auto = len(cases)
        counts = lane_counts(runs, args.lanes)
        compare_workers = cpu_workers(args.compare_workers, args.jobs)
    except MatrixError as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1

    if args.dry_run:
        print(f"CASES {len(cases)}: {' '.join(cases)}")
        print(
            f"MATRIX {n_matrix} explicit + {n_auto} auto = {n_matrix + n_auto} runs; "
            f"lanes={args.lanes} per_lane={counts}"
        )
        for run in runs:
            bunch = bunch_file(cases_dir, run.case, require=False)
            prefix = out_dir / ".work" / run.run_id / run.run_id
            m_argv = measurement_argv(
                args.binary,
                bunch,
                run,
                prefix,
                args.auto_count_arg,
                args.auto_count_edges,
            )
            c_argv = compare_argv(
                args.python, args.compare, prefix, run.requested_bins, compare_workers
            )
            print(
                f"RUN {run.index:02d} lane={run.lane} id={run.run_id} "
                f"kind={run.kind} K={run.requested_bins if run.requested_bins else 'auto'}"
            )
            print(f"  measure: {shlex.join(m_argv)}")
            print(f"  compare: {shlex.join(c_argv)}")
        for lane in range(args.lanes):
            members = [run.run_id for run in runs if run.lane == lane]
            print(f"LANE {lane} ({len(members)}): {' '.join(members)}")
        print(
            "PLAN_SUMMARY "
            + json.dumps(
                {
                    "cases": len(cases),
                    "matrix": n_matrix,
                    "auto_count": n_auto,
                    "total": n_matrix + n_auto,
                    "lanes": args.lanes,
                    "per_lane": counts,
                },
                sort_keys=True,
            )
        )
        return 0

    try:
        if not Path(args.binary).is_file():
            raise MatrixError(f"--binary is not a file: {args.binary}")
        if not os.access(args.binary, os.X_OK):
            raise MatrixError(f"--binary is not executable: {args.binary}")
        if not args.compare.is_file():
            raise MatrixError(f"comparison script not found: {args.compare}")
        for case in cases:
            bunch_file(cases_dir, case, require=True)
        out_dir.mkdir(parents=True, exist_ok=True)
        (out_dir / ".work").mkdir(parents=True, exist_ok=True)
    except (MatrixError, OSError) as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1

    selected = [run for run in runs if run.lane == args.lane]
    print(
        f"PLAN {n_matrix} explicit + {n_auto} auto = {n_matrix + n_auto} runs; "
        f"this lane {args.lane}/{args.lanes} runs {len(selected)}",
        flush=True,
    )
    for lane in range(args.lanes):
        members = [run.run_id for run in runs if run.lane == lane]
        print(f"LANE {lane} ({len(members)}): {' '.join(members)}", flush=True)

    print_lock = threading.Lock()
    rows_by_index: Dict[int, dict] = {}
    timeout = args.timeout if args.timeout > 0 else None

    def work(run: Run) -> dict:
        return execute_run(
            run,
            binary=args.binary,
            cases_dir=cases_dir,
            out_dir=out_dir,
            python=args.python,
            compare=args.compare,
            auto_count_arg=args.auto_count_arg,
            auto_count_edges=args.auto_count_edges,
            compare_workers=compare_workers,
            timeout=timeout,
            resume=args.resume,
            print_lock=print_lock,
        )

    try:
        if args.jobs == 1:
            for run in selected:
                rows_by_index[run.index] = work(run)
        else:
            with cf.ThreadPoolExecutor(max_workers=args.jobs) as pool:
                futures = {pool.submit(work, run): run for run in selected}
                for future in cf.as_completed(futures):
                    run = futures[future]
                    rows_by_index[run.index] = future.result()
    except MatrixError as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1
    except Exception as exc:  # noqa: BLE001 - report worker failures clearly
        print(f"run_matrix: unexpected failure: {exc}", file=sys.stderr)
        return 1

    lane_rows = [rows_by_index[run.index] for run in selected]
    lane_rows.sort(key=lambda row: row["index"])
    atomic_write_json(
        out_dir / f"manifest.lane{args.lane}of{args.lanes}.json",
        {
            "schema": SCHEMA,
            "lane": args.lane,
            "lanes": args.lanes,
            "runs": lane_rows,
        },
    )

    try:
        all_rows = merge_lane_manifests(out_dir, args.lanes)
        payload = assemble_manifest(
            lane_rows,
            all_rows,
            lane=args.lane,
            lanes=args.lanes,
            out_dir=out_dir,
            expected_matrix=n_matrix,
            expected_auto=n_auto,
            binary=args.binary,
            cases_dir=cases_dir,
            bins=args.bins,
            rules=args.rules,
        )
    except MatrixError as exc:
        print(f"run_matrix: {exc}", file=sys.stderr)
        return 1

    atomic_write_json(out_dir / "manifest.json", payload)
    missing = payload["missing_metrics"]
    print(
        "MISSING_METRICS " + json.dumps(missing, sort_keys=True),
        flush=True,
    )
    if payload["complete"]:
        print(
            f"MANIFEST complete rows={payload['counts']['rows']} "
            f"explicit={payload['counts']['explicit']} auto={payload['counts']['auto']}",
            flush=True,
        )
    else:
        pending = [i for i in range(args.lanes)
                   if not (out_dir / f"manifest.lane{i}of{args.lanes}.json").exists()]
        print(
            f"MANIFEST partial lane={args.lane}/{args.lanes} "
            f"rows={payload['counts']['rows']} pending_lanes={pending}",
            flush=True,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
