def aggregate_missing(rows: Sequence[dict]) -> Dict[str, dict]:
    missing: Dict[str, dict] = {}
    for row in rows:
        for key in row.get("missing_metrics", []):
            missing.setdefault(key, {"count": 0, "note": MISSING_METRIC_NOTES.get(key, "")})
            missing[key]["count"] += 1
    return missing


def verify_manifest(
    rows: Sequence[dict],
    out_dir: Path,
    expected_matrix: int,
    expected_auto: int,
) -> None:
    expected_total = expected_matrix + expected_auto
    if len(rows) != expected_total:
        raise MatrixError(
            f"manifest has {len(rows)} rows, expected {expected_total} "
            f"({expected_matrix} explicit + {expected_auto} auto)"
        )
    explicit = [row for row in rows if not row.get("auto_count")]
    auto = [row for row in rows if row.get("auto_count")]
    if len(explicit) != expected_matrix or len(auto) != expected_auto:
        raise MatrixError(
            f"manifest split is {len(explicit)} explicit + {len(auto)} auto, "
            f"expected {expected_matrix} + {expected_auto}"
        )
    ids = [row.get("id") for row in rows]
    if len(set(ids)) != len(ids):
        raise MatrixError("manifest has duplicate run ids; lanes overlapped")
    for row in rows:
        path = out_dir / row["output"]
        payload = valid_run_output(path)
        if payload is None:
            raise MatrixError(f"manifest output is missing: {path}")
        actual = sha256_file(path)
        if row.get("sha256") and row["sha256"] != actual:
            raise MatrixError(f"manifest sha256 mismatch for {path}")


def assemble_manifest(
    lane_rows: Sequence[dict],
    all_rows: Optional[Sequence[dict]],
    *,
    lane: int,
    lanes: int,
    out_dir: Path,
    expected_matrix: int,
    expected_auto: int,
    binary: str,
    cases_dir: Path,
    bins: Sequence[int],
    rules: Sequence[str],
    geometry: dict,
    geometry_name: str,
    profile: str,
) -> dict:
    complete = all_rows is not None
    rows = list(all_rows if complete else lane_rows)
    rows.sort(key=lambda row: row["index"])
    if complete:
        verify_manifest(rows, out_dir, expected_matrix, expected_auto)
    payload = {
        "schema": SCHEMA,
        "complete": complete,
        "lane": lane,
        "lanes": lanes,
        "binary": binary,
        "cases_dir": str(cases_dir),
        "out_dir": str(out_dir),
        "bins": list(bins),
        "rules": list(rules),
        "geometry": dict(geometry),
        "geometry_name": geometry_name,
        "profile": profile,
        "deterministic_deposit": True,
        "reference": {
            "nodes": "mask",
            "cache": "enabled",
            "cache_dir": str(reference_cache_dir(out_dir)),
            "key": "sha256(particles, grid, origin, cell, order, refine, eps, mask)",
            "note": "T depends only on the particles and geometry, so one entry "
                    "serves every rule and K of a case",
        },
        "auto_count": {
            "bins_arg": AUTO_COUNT_BINS_ARG,
            "velocity_bin_edges": AUTO_COUNT_EDGES,
            "note": "measure_velocity_bins.cpp:186 compares the literal 'auto'; "
                    "'0' would be an explicit one-box request",
        },
        "expected": {
            "total": expected_matrix + expected_auto,
            "explicit": expected_matrix,
            "auto": expected_auto,
        },
        "counts": {
            "rows": len(rows),
            "explicit": sum(1 for row in rows if not row.get("auto_count")),
            "auto": sum(1 for row in rows if row.get("auto_count")),
            "lane_rows": len(lane_rows),
        },
        "lane_assignment": {
            "lanes": lanes,
            "this_lane": lane,
            "runs_this_lane": len(lane_rows),
        },
        "missing_metrics": aggregate_missing(rows),
        "metric_sources": {
            "startup_us": "PREFIX_meta_B<B>.txt bin_derive_ms * 1000",
            "nonempty_bins": "PREFIX_bunch.txt distinct non-negative box_of values "
                             "(fallback: meta box_of)",
            "chosen_bins": "PREFIX_meta_B<B>.txt bins_used",
            "requested_bins": "PREFIX_meta_B<B>.txt requested_bins",
            "per_axis": "PREFIX_meta_B<B>.txt per_axis (total K over three axes)",
            "per_axis_rules": "PREFIX_meta_B<B>.txt axis_edges rule list",
            "in_bunch_max": "PREFIX_compare.json runs[B].metrics_v2.in_bunch.worst_rel",
            "far_field_max": "PREFIX_compare.json runs[B].metrics_v2.far_field.worst_rel",
            "p99_rel_rms_rel": "PREFIX_compare.json runs[B].metrics_v2.*.per_component",
            "proxy_error": "PREFIX_compare.json runs[B].model_error",
        },
        "runs": rows,
    }
    return payload


def merge_lane_manifests(out_dir: Path, lanes: int) -> Optional[List[dict]]:
    paths = [out_dir / f"manifest.lane{i}of{lanes}.json" for i in range(lanes)]
    if not all(path.exists() for path in paths):
        return None
    rows: List[dict] = []
    for path in paths:
        try:
            payload = json.loads(path.read_text())
        except (OSError, ValueError) as exc:
            raise MatrixError(f"cannot read lane manifest {path}: {exc}") from exc
        lane_rows = payload.get("runs")
        if not isinstance(lane_rows, list):
            raise MatrixError(f"lane manifest {path} has no runs list")
        rows.extend(lane_rows)
    rows.sort(key=lambda row: row["index"])
    return rows


